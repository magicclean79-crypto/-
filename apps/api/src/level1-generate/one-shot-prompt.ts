export type OneShotAssetRole =
  | "ACTUAL_PRODUCT"
  | "PACKAGING"
  | "LABEL"
  | "SPEC"
  | "BARCODE"
  | "MANUAL"
  | "LIFESTYLE"
  | "UNKNOWN";

export interface OneShotPromptAsset {
  role: OneShotAssetRole;
  index: number;
}

const ROLE_LABEL: Record<OneShotAssetRole, string> = {
  ACTUAL_PRODUCT:
    "실제 제품 사진 — 이 사진의 제품 형태·구조·구성품·색상·재질·크기 비율을 그대로 유지해야 합니다. 이 사진이 최우선 reference입니다.",
  PACKAGING:
    "포장 사진 — 제품 정보(문구·구성)를 확인하는 참고용입니다. 이 사진 속 포장 상자 자체를 제품 형태로 생성하지 마세요.",
  LABEL:
    "라벨/스티커 사진 — 제품명·브랜드·재질 등 텍스트 정보 확인용입니다. 형태 reference로 쓰지 마세요.",
  SPEC: "사양표 사진 — 규격·재질·구성품 등 텍스트 정보 확인용입니다. 형태 reference로 쓰지 마세요.",
  BARCODE: "바코드 사진 — 식별용입니다. 형태 reference로 쓰지 마세요.",
  MANUAL: "설명서 사진 — 사용법·구성품 정보 확인용입니다. 형태 reference로 쓰지 마세요.",
  LIFESTYLE: "사용 장면 참고 사진 — 배경·구도 분위기만 참고하고, 제품 형태는 실제 제품 사진을 따르세요.",
  UNKNOWN:
    "역할이 정해지지 않은 사진 — 사진 자체를 먼저 판단하세요. 실제 제품이 뚜렷이 보이면 '실제 제품 사진'으로, 포장·라벨·사양표·바코드·설명서로 보이면 '정보 확인용'으로 스스로 구분해서 사용하세요. 정보 확인용으로 판단한 사진은 제품 형태 reference로 쓰지 마세요.",
};

/**
 * LEVEL1 원샷 생성 프롬프트 (T1-189). 하나의 멀티모달 호출 안에서
 * "사진 분석 → 제품 이해 → 디자인 결정 → 최종 상세페이지 이미지 생성"을
 * 전부 지시한다. 텍스트 분석 결과를 별도로 돌려받지 않는다(모델 출력이
 * 이미지 1장으로 고정돼 있다 — `gemini-one-shot.client.ts` 참고) — 대신
 * 이 프롬프트 문장 자체가 "무엇을 분석하고 무엇을 결정하라고 시켰는지"의
 * 기록이 되어 생성 결과 metadata에 그대로 저장된다.
 */
export function buildOneShotPrompt(assets: OneShotPromptAsset[]): string {
  const legend = assets
    .map((asset) => `이미지 ${asset.index + 1}: ${ROLE_LABEL[asset.role]}`)
    .join("\n");

  return [
    "당신은 이커머스 상세페이지 디자이너입니다. 아래 제품 사진들을 보고, 하나의 완성된 상세페이지 이미지를 생성하세요.",
    "",
    "[입력 이미지 안내]",
    legend,
    "",
    "[해야 할 일 — 이 한 번의 생성 안에서 전부 수행]",
    "1. 이미지들을 보고 제품을 분석하세요: 제품명·브랜드·모델·소재·색상·규격·구성품을 사진에서 실제로 확인되는 만큼만 파악하세요. 사진에 없는 정보는 지어내지 마세요.",
    "2. 이 제품의 핵심 판매 포인트(왜 사고 싶은지)를 사진에서 확인되는 사실을 근거로 판단하세요.",
    "3. 상세페이지의 디자인 콘셉트·레이아웃·타이포그래피·색상·아이콘·그래픽을 이 제품에 어울리게 스스로 결정하세요.",
    "4. 그 결정을 반영해, 실제 제품 사진을 기반으로 한 완성된 상세페이지 이미지 1장을 생성하세요.",
    "",
    "[반드시 지켜야 할 제품 동일성 규칙 — 이미지 품질보다 항상 우선]",
    "- '실제 제품 사진'으로 표시된 이미지 속 제품의 형태·구조·구성품 개수·색상·재질·크기 비율을 절대 바꾸지 마세요.",
    "- 구성품을 추가하거나 삭제하지 마세요. 사진에 없는 제품·구성품을 새로 만들지 마세요.",
    "- 바꿔도 되는 것은 배경·조명·촬영 구도·분위기·연출뿐입니다.",
    "- 포장/라벨/사양표/바코드/설명서 사진은 정보 확인용으로만 쓰고, 그 사진 속 상자나 인쇄물 자체의 형태를 제품 형태로 생성하지 마세요.",
    "- 결과가 실제 제품과 다른 제품처럼 보이면 안 됩니다. 예쁜 이미지보다 제품 동일성이 항상 우선입니다.",
    "",
    "[출력]",
    "완성된 상세페이지 이미지 1장만 출력하세요. HTML이나 코드가 아니라 이미지 자체를 생성하세요.",
  ].join("\n");
}
