-- 무시 검토 알림 이력 (TASK-4401, Sprint 44 — CTO 정책 4401-③)
--
-- TASK-4301은 검토일이 지나면 무시를 자동으로 풀고 경보 채널로 돌려보냈다.
-- 그런데 그 경보는 담당자에게 가지 않는다 — 채널을 보는 사람과 항목을 맡은
-- 사람은 대개 다르고, 그러면 "돌아온 경보"가 다시 아무도 안 보는 자리에
-- 쌓인다.
--
-- 그래서 알림을 보내되, **같은 단계를 매일 다시 보내지 않기 위해** 무엇을
-- 언제 보냈는지 남긴다. 매일 같은 문장이 오면 그 알림부터 무시하게 되고,
-- 그러면 검토일 자체가 의미를 잃는다.
--
-- **이 칸들은 무시의 상태를 바꾸지 않는다.** 알림을 보냈다고 검토일이
-- 밀리거나 무시가 되살아나지 않는다 — 알림이 상태를 바꾸면 보내는 것만으로
-- 문제가 사라지는 셈이 된다.
ALTER TABLE "neglect_decisions" ADD COLUMN "lastStage" TEXT;
ALTER TABLE "neglect_decisions" ADD COLUMN "lastNotifiedAt" TIMESTAMP(3);
